DIALOGUE_TASK = """\
ЗАДАЧА: проанализируй последнее сообщение собеседника с учётом истории и состояния сделки и реши,
что делать дальше. Верни JSON строго по схеме.
- reply_text: текст ответа собеседнику или null, если отвечать не нужно (например, после opt_out или если
  нужна передача человеку и отвечать нечего).
- send_sticker_mood: настроение стикера/GIF из медиатеки владельца, только если это действительно уместно
  по тону; иначе "none". Стикеры не отправляются в серьёзных/конфликтных моментах.
- state_update: только то, что ЯВНО прозвучало в переписке. Цены — строкой с числом как в переписке.
  Неизвестное — null.
- ready_for_deal: true, только если товар, количество, цена и валюта согласованы обеими сторонами.
"""


def build_dialogue_system(config: AIConfigVersion | None, owner_style: str, language: str) -> str:
    parts = [HARD_RULES]
    if config is not None:
        parts.append(f"ГЛОБАЛЬНЫЕ ИНСТРУКЦИИ АДМИНИСТРАТОРА (версия {config.version}):")
        for title, body in (
            ("Общие инструкции", config.instructions),
            ("Стиль общения", config.style),
            ("Правила переговоров", config.negotiation_rules),
            ("Правила торговли", config.trading_rules),
        ):
            if body and body.strip():
                parts.append(f"## {title}\n{body.strip()}")
        if config.examples:
            parts.append("## Примеры\n" + json.dumps(config.examples, ensure_ascii=False, indent=1))
    if owner_style.strip():
        parts.append(f"ПОЖЕЛАНИЯ ВЛАДЕЛЬЦА К СТИЛЮ:\n{owner_style.strip()}")
    parts.append(f"Основной язык общения: {language}. Если собеседник пишет на другом языке — отвечай на его языке.")
    parts.append(DIALOGUE_TASK)
    return "\n\n".join(parts)


def render_transcript(messages: list[dict[str, Any]]) -> str:
    """messages: [{"sender": contact|owner|agent, "text": ..., "media": {...}|None, "at": iso}]."""
    lines = []
    who = {"contact": "СОБЕСЕДНИК", "owner": "ВЛАДЕЛЕЦ (вручную)", "agent": "ТЫ (агент)"}
    for m in messages:
        body = m.get("text") or ""
        media = m.get("media")
        if media:
            if media.get("ok"):
                body += f"\n[{media.get('kind')}: {media.get('summary')}]"
            else:
                body += f"\n[{media.get('kind')}: не удалось проанализировать — {media.get('error')}]"
        lines.append(f"<message from=\"{who.get(m['sender'], m['sender'])}\" at=\"{m.get('at', '')}\">\n{body}\n</message>")
    return "\n".join(lines)


def build_dialogue_content(
    *,
    transcript: list[dict[str, Any]],
    state: dict[str, Any],
    trade_bot: dict[str, Any] | None,
    limits: dict[str, Any],
    contact_profile: dict[str, Any],
    sticker_moods: list[str],
    market_context: str | None,
    is_new_conversation: bool,
) -> list[dict[str, Any]]:
    blocks = [
        "<deal_state>\n" + json.dumps(state, ensure_ascii=False, indent=1) + "\n</deal_state>",
        "<trade_bot>\n"
        + (json.dumps(trade_bot, ensure_ascii=False) if trade_bot else "НЕ УКАЗАН — сделки создавать нельзя")
        + "\n</trade_bot>",
        "<owner_limits>\n" + json.dumps(limits, ensure_ascii=False, default=str) + "\n</owner_limits>",
        "<contact_profile source=\"только данные из источника\">\n"
        + json.dumps(contact_profile, ensure_ascii=False)
        + "\n</contact_profile>",
        "<available_sticker_moods>" + ", ".join(sticker_moods or ["нет медиатеки"]) + "</available_sticker_moods>",
    ]
    if market_context:
        blocks.append("<market_data>\n" + market_context + "\n</market_data>")
    if is_new_conversation:
        blocks.append("<note>Это новый диалог: собеседник написал первым.</note>")
    blocks.append("<conversation>\n" + render_transcript(transcript) + "\n</conversation>")
    return [{"type": "text", "text": "\n\n".join(blocks)}]


